#!/usr/bin/env lua5.4
-- gen-manual.lua — render docs/MANUAL.md from the controller script itself.
--
-- The manual is GENERATED: the single source of truth is the ACTIONS table
-- (and the palette / mixer tables) inside script/LaunchpadMiniMK3.lua. Run
-- tools/gen-manual.sh to regenerate; tests/run-tests.sh fails when the
-- committed manual is stale.
--
-- Usage: tools/gen-manual.lua [source.lua] [output.md]

local src = arg[1] or "script/LaunchpadMiniMK3.lua"
local out = arg[2] or "docs/MANUAL.md"

package.path = "./tests/?.lua;" .. package.path
local mock = require("mock-mpc")
_G.mpc = mock.mpc
_G.dev = mock.dev
_G.LaunchpadMiniMK3 = mock.dev
dofile(os.getenv("LPMINI_LUA") or src)

local L = LaunchpadMiniMK3
local ACTIONS = L.ACTIONS
assert(type(ACTIONS) == "table", "the script did not expose ACTIONS")
local P = L.PALETTE
assert(type(P) == "table", "the script did not expose PALETTE")
local MIXER = L.MIXER
assert(type(MIXER) == "table", "the script did not expose MIXER")

local groups = {
	{ title = "Top row (CC 91-98)", ccs = { 91, 92, 93, 94, 95, 96, 97, 98 } },
	{ title = "Right column (CC 89-19, top to bottom)", ccs = { 89, 79, 69, 59, 49, 39, 29, 19 } },
}

local lines = {}
local function add(s)
	lines[#lines + 1] = s or ""
end

local function colourRow(name, c)
	return string.format("| %s | %d, %d, %d |", name, c[1], c[2], c[3])
end

add("# Launchpad Mini MK3 controller manual")
add()
add("Generated from `script/LaunchpadMiniMK3.lua` by `tools/gen-manual.sh`.")
add("Do not edit this file: edit the script and regenerate.")
add()
add("## Grid")
add()
add("The 8x8 pads are notes 11-88, bottom-left first (the same numbering as the")
add("Launchpad Pro MK3). The pad window shows the MPC clip matrix; the arrows move")
add("the window. Row 0 is the top row of pads. Pad press launches the clip under")
add("it; a pad press selects and launches the clip under it.")
add()
add("```")
add("  top row:  91 Up   92 Down   93 Left   94 Right   95 Session")
add("            96 Drums (MPC pads)   97 Keys (Pad Perform)")
add("            98 User (Q-Link page)")
add("  right:    89 Scene 1   79 Scene 2   69 Scene 3   59 Scene 4   49 Scene 5")
add("            39 Scene 6   29 Scene 7   19 MIXER menu (bottom-right corner)")
add("```")
add()
add("There is no Shift: the Novation logo is not a button on the Mini MK3.")
add()
add("## MIXER menu (CC 19)")
add()
add("All six per-track functions are exposed at the same time, one row each, one")
add("column per track (the columns follow the clip window, so the mixer lines up")
add("with the clip grid):")
add()
add("```")
for _, m in ipairs(MIXER) do
	if m.perTrack then
		add(string.format("  row %d (notes %d-%d)   %s: one pad per track column", m.row, 10 * (8 - m.row) + 1, 10 * (8 - m.row) + 8, m.label))
	else
		add(string.format("  row %d (notes %d-%d)   %s:", m.row, 10 * (8 - m.row) + 1, 10 * (8 - m.row) + 8, m.label))
		for i, item in ipairs(m.items) do
			add(string.format("      col %d (note %d): %s", i - 1, 10 * (8 - m.row) + i, item))
		end
	end
end
add("```")
add()
add("Press CC 19 again (or Session) to close the mixer; CC 19 also closes any open")
add("page (fader menu, tempo, swing, Q-Link) first. The record row starts a")
add("clip recording (arm + trigger the first empty slot) and stops it again.")
add()
add("## Buttons")
add()
for _, g in ipairs(groups) do
	add("### " .. g.title)
	add()
	add("| CC | Button | Press |")
	add("| --- | --- | --- |")
	for _, cc in ipairs(g.ccs) do
		local a = ACTIONS[cc]
		assert(a ~= nil, "CC " .. cc .. " missing from ACTIONS")
		add(string.format("| %d | %s | %s |", cc, a.label, a.plain))
	end
	add()
end
add("## LED colours")
add()
add("| Colour | R, G, B (0-127) |")
add("| --- | --- |")
local paletteOrder = { "off", "dim", "available", "white", "green", "red", "orange", "blue", "cyan", "magenta", "yellow" }
for _, name in ipairs(paletteOrder) do
	add(colourRow(name, P[name]))
end

local fh = assert(io.open(out, "w"))
fh:write(table.concat(lines, "\n"), "\n")
fh:close()
io.write("wrote ", out, "\n")
